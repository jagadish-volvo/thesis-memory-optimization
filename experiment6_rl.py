# WORKFLOW ENVIRONMENT
# ============================================================

class WorkflowEnvironment:
    """
    Simulates the Volvo verification workflow environment.

    IMPORTANT — Decision latency measurement:
    Decision latency is measured using time.perf_counter() —
    actual wall-clock time for each routing decision.

    Static agent: evaluates a fixed rule (O(1) dictionary lookup)
    RL agent:     looks up Q-table (O(1) but with state construction
                  overhead that decreases as table stabilises)

    This gives a REAL measurement not a hardcoded value.
    The difference reflects actual computational cost of each approach.
    """

    def __init__(self, task_sequence, proc_time):
        self.task_sequence = task_sequence
        self.proc_time     = proc_time
        self.reset()

    def reset(self):
        self.task_index      = 0
        self.clock           = 0.0
        self.agent_queues    = [[] for _ in range(NUM_AGENTS)]
        self.agent_finish    = [0.0] * NUM_AGENTS
        self.last_assign     = 0.0
        self.completed       = []
        self.wait_times      = []
        self.decision_lats   = []   # real measured latencies
        self.tasks_per_agent = [0] * NUM_AGENTS

    def _free(self, agent_id):
        return self.agent_finish[agent_id] <= self.clock

    def _qlen(self, agent_id):
        return len(self.agent_queues[agent_id])

    def _build_state(self, task):
        """
        State vector for Q-table (thesis proposal §4.2):
          task_type, priority, queue_bins × 5, availability × 5, time_bin
        """
        qbins = []
        for i in range(NUM_AGENTS):
            q = self._qlen(i)
            qbins.append(0 if q == 0 else 1 if q <= 3 else 2)
        avail = [1 if self._free(i) else 0 for i in range(NUM_AGENTS)]
        gap   = self.clock - self.last_assign
        tbin  = 0 if gap < 2.0 else 1 if gap < 5.0 else 2
        return (task["task_type"], task["priority"],
                *qbins, *avail, tbin)

    def _process_queues(self):
        for agent_id in range(NUM_AGENTS):
            if self._free(agent_id) and self.agent_queues[agent_id]:
                next_task = self.agent_queues[agent_id].pop(0)
                ptime = self.proc_time[agent_id][next_task["task_type"]]
                ptime *= (0.8 if next_task["priority"] == 2 else
                          1.2 if next_task["priority"] == 0 else 1.0)
                self.agent_finish[agent_id] = self.clock + ptime
                self.completed.append({
                    "agent":       agent_id,
                    "task":        next_task,
                    "finish_time": self.agent_finish[agent_id]
                })

    def step(self, task, action, decision_time_ns):
        """
        Route task to chosen agent.

        decision_time_ns : actual time taken to make routing decision
                           measured by caller using time.perf_counter_ns()
                           This is NOT hardcoded — it is measured in real time
        """
        self.clock = task["arrival_time"]
        self._process_queues()

        # Store real measured decision latency (convert ns to ms)
        self.decision_lats.append(decision_time_ns / 1_000_000)

        specialist  = task["task_type"]
        q_len       = self._qlen(action)
        is_free     = self._free(action)
        spec_q      = self._qlen(specialist)
        spec_free   = self._free(specialist)
        idle_agents = [
            i for i in range(NUM_AGENTS)
            if self._free(i) and self._qlen(i) == 0
        ]

        # ── REWARD (thesis proposal §4.2) ───────────────────
        reward = 0.0

        if action == specialist and is_free and q_len == 0:
            reward = 2.0                        # best — specialist free

        elif (action != specialist and
              spec_q >= 3 and not spec_free and
              is_free and q_len == 0):
            reward = 1.5                        # smart overflow routing

        elif action == specialist and q_len <= 2:
            reward = 0.8                        # specialist short queue

        elif action != specialist and is_free and q_len == 0:
            reward = 0.3                        # free non-specialist

        elif q_len >= 4 and len(idle_agents) > 0:
            reward = -1.5                       # idle agents wasted

        elif q_len >= MAX_QUEUE - 1:
            reward = -2.0                       # queue nearly full

        else:
            reward = -0.2                       # minor inefficiency

        if task["priority"] == 2:
            reward *= 1.4
        elif task["priority"] == 0:
            reward *= 0.7

        if len(idle_agents) >= 3 and q_len >= 3:
            reward -= 0.5

        # ── ASSIGN TASK ─────────────────────────────────────
        self.tasks_per_agent[action] += 1
        self.last_assign = self.clock

        if is_free and q_len == 0:
            ptime = self.proc_time[action][task["task_type"]]
            ptime *= (0.8 if task["priority"] == 2 else
                      1.2 if task["priority"] == 0 else 1.0)
            self.agent_finish[action] = self.clock + ptime
            self.completed.append({
                "agent": action, "task": task,
                "finish_time": self.agent_finish[action]
            })
            wait = 0.0
        elif q_len < MAX_QUEUE:
            self.agent_queues[action].append(task)
            wait = max(0, self.agent_finish[action] - self.clock)
        else:
            wait   = 99.0
            reward -= 2.0

        self.wait_times.append(wait)

        self.task_index += 1
        done = self.task_index >= len(self.task_sequence)
        if not done:
            next_task  = self.task_sequence[self.task_index]
            next_state = self._build_state(next_task)
        else:
            next_task  = None
            next_state = None

        return next_state, next_task, reward, done

    def get_metrics(self):
        """
        Calculate thesis KPIs.
        Decision latency is real measured time — not hardcoded.
        KPI 1 is TOTAL orchestration processing time per scenario
        (sum of all routing decision times) — as per Hafid feedback.
        """
        if not self.completed:
            return {
                "orch_total_time_ms":   0.0,
                "avg_decision_lat_ms":  0.0,
                "resource_utilisation": 0.0,
                "avg_wait_time":        0.0,
                "tasks_per_agent":      [0] * NUM_AGENTS
            }

        # KPI 1 — Total orchestration processing time
        # Sum of ALL routing decision times in this scenario
        # Static: fast per decision but makes poor routing choices
        # RL: slightly more per decision but makes smarter choices
        # Overall total reflects orchestration layer efficiency
        total_orch_time_ms = sum(self.decision_lats)

        # Per-decision average (supporting metric)
        avg_latency_ms = (
            sum(self.decision_lats) / len(self.decision_lats)
            if self.decision_lats else 0.0
        )

        # KPI 2 — Resource utilisation (load balance)
        total = sum(self.tasks_per_agent)
        if total == 0:
            resource_util = 0.0
        else:
            ideal     = total / NUM_AGENTS
            imbalance = sum(abs(self.tasks_per_agent[i] - ideal)
                            for i in range(NUM_AGENTS))
            resource_util = max(0.0, 1.0 - imbalance / (2 * total))

        # KPI 3 — Average task wait time
        avg_wait = (
            sum(w for w in self.wait_times if w < 90) /
            max(1, sum(1 for w in self.wait_times if w < 90))
        )

        return {
            "orch_total_time_ms":   round(total_orch_time_ms, 4),
            "avg_decision_lat_ms":  round(avg_latency_ms, 6),
            "resource_utilisation": round(resource_util, 4),
            "avg_wait_time":        round(avg_wait, 3),
            "tasks_per_agent":      list(self.tasks_per_agent)
        }


