def pct(b, r, higher_better=False):
    bm = np.mean(b)
    rm = np.mean(r)
    if bm == 0:
        return 0.0
    return round(((bm - rm) / bm * 100) if not higher_better
                 else ((rm - bm) / bm * 100), 1)

