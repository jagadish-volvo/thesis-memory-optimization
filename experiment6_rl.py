def get_proc_times(metadata):
    spec     = metadata["processing_times"]["specialist_agent_seconds"]
    non_spec = metadata["processing_times"]["non_specialist_agent_seconds"]
    return {
        agent_id: {
            task_type: spec if agent_id == task_type else non_spec
            for task_type in range(NUM_AGENTS)
        }
        for agent_id in range(NUM_AGENTS)
    }


