# Q-LEARNING AGENT
# ============================================================

class QLearningAgent:
    """
    Q-learning adaptive coordination agent.
    Learns optimal routing policy from synthetic dataset.
    Decision latency measured in real wall-clock time.
    """

    def __init__(self,
                 learning_rate   = 0.15,
                 discount_factor = 0.95,
                 epsilon_start   = 1.0,
                 epsilon_min     = 0.05,
                 epsilon_decay   = 0.9908):
        self.lr            = learning_rate
        self.gamma         = discount_factor
        self.epsilon       = epsilon_start
        self.epsilon_min   = epsilon_min
        self.epsilon_decay = epsilon_decay
        self.q_table       = defaultdict(lambda: np.zeros(NUM_AGENTS))
        self.epsilon_log   = []

    def select_action(self, state, explore=True):
        """
        Epsilon-greedy selection.
        Returns (action, time_ns) where time_ns is real decision time.
        """
        t_start = time.perf_counter_ns()

        if explore and random.random() < self.epsilon:
            action = random.randint(0, NUM_AGENTS - 1)
        else:
            action = int(np.argmax(self.q_table[state]))

        t_end = time.perf_counter_ns()
        return action, (t_end - t_start)

    def update(self, state, action, reward, next_state):
        current = self.q_table[state][action]
        target  = reward + self.gamma * np.max(self.q_table[next_state])
        self.q_table[state][action] += self.lr * (target - current)

    def decay_epsilon(self):
        self.epsilon = max(self.epsilon_min,
                           self.epsilon * self.epsilon_decay)
        self.epsilon_log.append(self.epsilon)


# ============================================================
# STATIC BASELINE AGENT
# ============================================================

class StaticCoordinationPolicy:
    """
    Static policy — always routes task type X to agent X.
    Decision latency measured in real wall-clock time.
    """

    def select_action(self, state):
        """
        Returns (action, time_ns) where time_ns is real decision time.
        Static policy: simple dictionary lookup — very fast.
        """
        t_start = time.perf_counter_ns()
        action  = state[0]   # task_type → same agent always
        t_end   = time.perf_counter_ns()
        return action, (t_end - t_start)


# ============================================================
# RUN ONE SCENARIO
# ============================================================

def run_scenario(agent, task_sequence, proc_time,
                 is_rl=True, explore=True):
    """Run one complete scenario. Returns reward and metrics."""
    env   = WorkflowEnvironment(task_sequence, proc_time)
    env.reset()

    task       = task_sequence[0]
    state      = env._build_state(task)
    total_rew  = 0.0

    while True:
        # Measure real decision time
        if is_rl:
            action, d_time_ns = agent.select_action(state, explore=explore)
        else:
            action, d_time_ns = agent.select_action(state)

        next_state, next_task, reward, done = env.step(
            task, action, d_time_ns
        )

        if is_rl and explore and next_state is not None:
            agent.update(state, action, reward, next_state)

        total_rew += reward

        if done or next_task is None:
            break

        state = next_state
        task  = next_task

    return total_rew, env.get_metrics()


